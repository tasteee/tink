// Generates dist/react.d.ts: JSX typings so a React + TypeScript app can use
// every public zest element with its real props, with no hand-written
// declarations. It is built from custom-elements.json, so it can never name
// an element or a prop the package does not ship.
//
// Use it from the app:
//
//   /// <reference types="@tasteee/zest/react" />
//
// or add "@tasteee/zest/react" to `types` in tsconfig.json.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const manifest = JSON.parse(readFileSync(join(root, 'custom-elements.json'), 'utf8'))
const elements = manifest.modules.flatMap((module) => module.declarations ?? []).filter((declaration) => declaration.customElement)

// A manifest type is used as written only when it is made of nothing but
// primitives, literals, arrays and object shapes. Anything that names a type
// the consumer cannot import becomes `unknown`: still accepted, never wrong.
const knownWords = new Set(['string', 'number', 'boolean', 'unknown', 'null', 'undefined', 'Array', 'File', 'Record', 'true', 'false'])

const isSelfContained = (typeText) => {
	const withoutStrings = typeText.replace(/'[^']*'/g, '').replace(/"[^"]*"/g, '')
	for (const match of withoutStrings.matchAll(/([A-Za-z_]\w*)(\s*\??\s*:)?/g)) {
		const isObjectKey = Boolean(match[2])
		if (isObjectKey) continue
		if (!knownWords.has(match[1])) return false
	}
	return true
}

const getPropType = (typeText) => {
	const text = typeText.replace(/\s+/g, ' ').trim()
	if (!text) return 'unknown'
	return isSelfContained(text) ? text : 'unknown'
}

const getEventDetail = (event) => {
	const detail = (event.detail ?? 'void').replace(/\s+/g, ' ').trim()
	if (detail === 'void') return 'null'
	return isSelfContained(detail) ? detail : 'unknown'
}

const renderElement = (declaration) => {
	const propLines = (declaration.attributes ?? []).map((attribute) => `\t\t${attribute.fieldName}?: ${getPropType(attribute.type?.text ?? '')}`)
	const eventLines = (declaration.events ?? []).map((event) => `\t\ton${event.name}?: (event: CustomEvent<${getEventDetail(event)}>) => void`)
	const lines = [...propLines, ...eventLines]
	const body = lines.length ? `{\n${lines.join('\n')}\n\t}` : '{}'
	return `\t\t\t\t'${declaration.tagName}': ZestProps<${body.replace(/\n\t/g, '\n\t\t\t\t')}>`
}

const header = `// Generated by scripts/build-jsx-types.mjs from custom-elements.json. Do not edit.
//
// JSX typings for the zest elements in React. Add this once:
//
//   /// <reference types="@tasteee/zest/react" />
//
// Props are the element's camelCase properties (\`isOpen\`, not \`is-open\`).
// Events are lowercase handlers named after the event: \`onchange\`, \`onselect\`.
import type * as React from 'react'

type ZestBaseProps = React.DetailedHTMLProps<React.HTMLAttributes<HTMLElement>, HTMLElement> & { class?: string }
type ZestProps<Own> = ZestBaseProps & Own

declare global {
\tnamespace React {
\t\tnamespace JSX {
\t\t\tinterface IntrinsicElements {
`

const footer = `\t\t\t}
\t\t}
\t}
}

export {}
`

const body = elements.map(renderElement).join('\n')
writeFileSync(join(root, 'dist', 'react.d.ts'), header + body + '\n' + footer)
console.log(`react.d.ts: ${elements.length} elements`)
